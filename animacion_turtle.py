import  turtle

t=turtle.Turtle()
screen=turtle.Screen()
screen.bgcolor("black")
t.color("blue")
t.begin_fill()
t.left(45)
t.forward(100)
t.left(90)
t.forward(100)
t.left(90)
t.forward(100)
t.left(90)
t.forward(100)
t.end_fill()
t.goto(0,250)
t.color("green")
t.begin_fill()
t.circle(50)
t.end_fill()
turtle.done()
